/* PQ2-native prefill candidates. Packed source codes and original half
 * block scales are retained. Each 128-value activation block is prepared
 * once and reused by every output tile. Integer partials are scaled into
 * FP32 with the original PQ2 scale in block modes. Staged full-K modes
 * explicitly requantize decoded weight rows and retain one matrix pair.
 * Signed INT2 uses (code xor 2) = code - 2; adding sum(x) restores code - 1.
 * Half2 retains FP16 activations; FP8 uses E4M3 codes exactly for weights.
 * Compile-selected row tiles and SIMD-group counts share the same binary. */

