#!/usr/bin/env python3
"""Render the M6 INT8 report exclusively from recorded benchmark JSON."""
from __future__ import annotations
import argparse
import json
from pathlib import Path


def load(path):
    return json.loads(path.read_text())


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("results", type=Path)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    isolated = load(args.results / "isolated/summary.json")
    models = load(args.results / "models/summary.json")
    tuning = load(args.results / "tuning-rowwise/tuning-summary.json")
    meta = load(args.results / "models/metadata.json")
    speedups=[r['paired_prefill_speedup'] for r in models['performance']]
    conclusion=(f"**The tuned INT8 model path reaches {min(speedups):.3f}–{max(speedups):.3f}× "
                "the existing Metal FP16 prefill rate on this model/length sweep. "
                "Keep it experimental and opt-in.**")
    lines = ["# M6: isolated precision and row-scaled INT8 prefill", "", conclusion, "",
             "Generated by `tools/report_metal_int8.py`; source data, executable/model SHA-256 hashes, "
             "power and thermal samples are in `raw/" + args.results.name + "/`.", "",
             f"Host: **{meta['cpu']}**. OS: `{meta['os'].replace(chr(10), '; ')}`.",
             f"Model benchmark revision: `{meta['revision']}`. "
             f"Cycles: {meta['cycles']}; tile rows: {meta['protocol']['int8_tile_rows']}.", "",
             "Models: " + "; ".join(f"`{label}` = `{Path(info['path']).name}`" for label,info in meta['models'].items()) + ".", "",
             "## Isolated prepared-operand GEMM", "",
             "Median GPU time per dispatch, 32 repetitions per command buffer, six interleaved cycles. "
             "Identical 128×64 tile, eight SIMD groups and FP32/INT32 outputs. "
             "Integer-valued operands are exactly representable in all formats; "
             "32 sampled outputs per run match an independent CPU dot exactly. "
             "This checks arithmetic plumbing, not realistic quantization quality.", "",
             "| M×N×K | FP16 µs / TFLOP/s | FP8 µs / TFLOP/s | INT8 µs / TOP/s | FP8 / FP16 rate | INT8 / FP16 rate |",
             "|---|---:|---:|---:|---:|---:|"]
    shapes = list(dict.fromkeys((r['m'], r['n'], r['k']) for r in isolated))
    for shape in shapes:
        modes = {r['mode']: r for r in isolated if (r['m'], r['n'], r['k']) == shape}
        vals = [modes[m]['gemm'] for m in ('f16', 'fp8', 'i8')]
        base = vals[0]['gpu_us']
        lines.append('| ' + '×'.join(map(str, shape)) + ' | ' + ' | '.join(
            f"{v['gpu_us']:.2f} / {v['tflops_or_tops']:.2f}" for v in vals) +
            f" | {base/vals[1]['gpu_us']:.3f}× | {base/vals[2]['gpu_us']:.3f}× |")
    lines += ["", "## Isolated precision quality", "",
              "Separate uniform and outlier fixtures contain non-integer values. Every format consumes "
              "the same normalized FP32 source, with a fixed scale of 1/16 in real units and no clipping. "
              "Errors use 32 sampled CPU-double dot products, not the exactly representable timing inputs. "
              "This measures format rounding under this fixed normalization; it is not model quality "
              "or the final path's rowwise quantization policy.", "",
              "| M×N×K | Fixture | Format | Sampled NRMSE | Cosine | Max absolute error (real units) |",
              "|---|---|---|---:|---:|---:|"]
    for r in load(args.results / "isolated/quality.json"):
        lines.append(f"| {r['m']}×{r['n']}×{r['k']} | {r['fixture']} | {r['mode']} | {r['nrmse']:.8f} | {r['cosine']:.8f} | {r['max_abs_real_units']:.6f} |")
    lines += ["", "## Conversion and operand memory", "",
              "Simple conversion packs both FP32 operands. Combined timing includes that conversion and GEMM. "
              "Calibrate32 separately includes a block maximum, scale calculation and packing; "
              "INT8 also computes a block sum. It is not added to the prepared GEMM result. "
              "The calibration oracle checks 32 sampled blocks. All modes retain identical padded strides.", "",
              "| M×N×K | Format | Convert µs | Combined µs | Calibrate32 µs | Packed operands MiB | Output MiB |",
              "|---|---|---:|---:|---:|---:|---:|"]
    for r in isolated:
        cal = f"{r['calibrate32']['gpu_us']:.2f}" if 'calibrate32' in r else '—'
        lines.append(f"| {r['m']}×{r['n']}×{r['k']} | {r['mode']} | {r['convert']['gpu_us']:.2f} | "
                     f"{r['combined']['gpu_us']:.2f} | {cal} | {r['operand_bytes']/2**20:.3f} | "
                     f"{r['output_bytes']/2**20:.3f} |")
    lines += ["", "Eight-bit operand storage is half FP16 storage. These are logical operand allocations, "
              "not peak process memory: the harness retains the FP32 source, all three packed variants, "
              "output and calibration metadata. Metadata adds one byte per 32 FP8 values or eight bytes "
              "per 32 INT8 values. Raw rows include GPU and CPU wall times.", "",
              "## Full-model comparison", "",
              "Same release executable, GGUF, synthetic prompt IDs and settings for both arms. "
              "Metal 4 tensor FP16 baseline versus opt-in INT8, six AB/BA cycles, pp128/pp512, "
              "32 decode steps, warmup 512, four CPU threads. Actual INT8 dispatch counts must be nonzero "
              "in the native arm and zero in the baseline; these counters are cumulative and include warmup. RSS is sampled after each point; backend bytes "
              "come from Metal `currentAllocatedSize`. Both are MiB, not a peak-memory profiler; do not add RSS and Metal bytes. "
              "INT8 retains original mapped weights and adds grow-only scratch of "
              "`(rows + n_out) * (K + 4)` bytes for row-scaled prepared X and W, including FP32 scales. "
              "The scale is the smallest power of two covering `amax / 127` (minimum normal FP32). "
              "Zero rows use scale 1. This adds both activation and weight error and does not reduce model storage.", "",
              "| Model | Prompt | FP16 / INT8 prefill t/s | Paired speedup (range) | FP16 / INT8 decode t/s | FP16 / INT8 RSS MiB | FP16 / INT8 backend MiB |",
              "|---|---:|---:|---:|---:|---:|---:|"]
    for r in models['performance']:
        a,b=r['metal4'],r['int8'];lo,hi=r['paired_prefill_speedup_range']
        lines.append(f"| {r['model']} | {r['seq_len']} | {a['prefill_tps']:.1f} / {b['prefill_tps']:.1f} | "
                     f"{r['paired_prefill_speedup']:.3f}× ({lo:.3f}–{hi:.3f}) | "
                     f"{a['decode_tps']:.1f} / {b['decode_tps']:.1f} | {a['rss_mb']:.1f} / {b['rss_mb']:.1f} | "
                     f"{a['backend_allocated_mb']:.1f} / {b['backend_allocated_mb']:.1f} |")
    lines += ["", "These are paired same-binary mode comparisons, not a clean-revision A/B no-regression gate. "
              "Decode retains the existing kernel; small timing differences are not an INT8 decode improvement. "
              "Prompt and model coverage is limited; the path remains opt-in.", "",
              "## Output quality", "",
              "Twelve self-authored completion tasks per model, including German, Python and reasoning, "
              "with a common natural-language prefix and at least 128 prompt tokens. Token IDs must match "
              "between arms. Profile logs prove native quantization dispatches occurred during quality runs. "
              "Mean NLL is teacher-forced continuation NLL; the PPL ratio is conditional on this small corpus, "
              "not a standard perplexity benchmark. Greedy generation compares 24 token IDs, including steps after EOS. GEN text is recorded separately with normalized whitespace.", "",
              "| Model | Continuation tokens | FP16 / INT8 mean NLL | Conditional PPL ratio | First token matches | Exact 24-token generations |",
              "|---|---:|---:|---:|---:|---:|"]
    for r in models['quality']:
        lines.append(f"| {r['model']} | {r['continuation_tokens']} | {r['mean_nll']['metal4']:.6f} / "
                     f"{r['mean_nll']['int8']:.6f} | {r['conditional_ppl_ratio']:.6f} | "
                     f"{r['first_token_matches']}/{r['cases']} | {r['exact_generations']}/{r['cases']} |")
    lines += ["", "Full-vocabulary next-token logits on three long prompts per model:", "",
              "| Model | Case | Top-1 same | Top-5 / top-10 overlap | Centered cosine | Centered RMSE | JS nats |",
              "|---|---|---|---:|---:|---:|---:|"]
    for r in models['logits']:
        lines.append(f"| {r['model']} | {r['case']} | {r['top1_same']} | {r['top5_overlap']}/5 / "
                     f"{r['top10_overlap']}/10 | {r['centered_cosine']:.6f} | {r['centered_rmse']:.6f} | {r['js_nats']:.6f} |")
    lines += ["", "Binary logits stay local; raw quality JSONL includes prompt/continuation IDs, per-token scores "
              "and greedy outputs. These smoke checks do not establish general task accuracy or long-context quality.", "",
              "## Tile tuning", "",
              "Six rotated-order cycles at pp512, eight decode steps. Same binary and thermal/power gate.", "",
              "| Model | Row tile | Median prefill t/s |", "|---|---:|---:|"]
    for r in tuning:
        lines.append(f"| {r['model']} | {r['tile_rows']} | {r['prefill_tps']:.1f} |")
    block=load(args.results / "block-models/summary.json")
    lines += ["", "## Initial blockwise implementation", "",
              "An earlier implementation preserved arbitrary original GGUF weight block scales and "
              "used 32-term integer dots with FP32 rescaling, quantizing activations per block. "
              "Its best row tile was 64. That exploratory run warmed 16 tokens; the final run warms 512 to exercise native preparation before timing. The final implementation prepares rows once and uses full-K "
              "integer dots with one post-scale. Each implementation has its own same-binary FP16/INT8 "
              "comparison; revisions and executable hashes are recorded separately. This exploratory "
              "comparison is not a clean-revision A/B performance gate.", "",
              "| Model | Prompt | Initial INT8 / FP16 | Final INT8 / FP16 |",
              "|---|---:|---:|---:|"]
    for r in block['performance']:
        final=next(x for x in models['performance'] if x['model']==r['model'] and x['seq_len']==r['seq_len'])
        lines.append(f"| {r['model']} | {r['seq_len']} | {r['paired_prefill_speedup']:.3f}× | {final['paired_prefill_speedup']:.3f}× |")
    lines += ["", "The isolated GEMM advantage is real on these controlled inputs, but preparing "
              "weights/activations and reading expanded temporary matrices still costs time and memory. "
              "The final path avoids per-block FP32 rescaling inside GEMM, at the cost of coarser "
              "rowwise quantization. K is capped at 65,536 to bound worst-case INT32 sums. "
              "A separate native INT8/E8M0 scale-plane prototype compiled but did not complete GPU "
              "dispatches on this driver within the test timeout; it was discarded and is not in this PR. "
              "The completed comparisons use ordinary INT8 tensors and explicit post-scaling.", "",
              "## Reproduce", "", "```sh",
              "python3 tools/bench_metal_precision.py --out /tmp/m6/isolated",
              "python3 tools/bench_metal_int8.py --tune-only --model NAME=/path/to/model.gguf --out /tmp/m6/tuning-rowwise",
              "python3 tools/bench_metal_int8.py --tile-rows 128 --model NAME=/path/to/model.gguf --out /tmp/m6/models",
              "python3 tools/report_metal_int8.py benchmark/results/raw/"+args.results.name+" --out benchmark/results/M6_INT8.md",
              "```", "", "Run measurement commands under an exclusive host lease. "
              "Build commands and scope are in `docs/BACKENDS.md`. The generator also reads "
              "the recorded initial blockwise run; that run can be reproduced at its recorded revision.", ""]
    validation=load(args.results / "validation.json")
    lines += ["## Validation", ""]
    for mode in ('release','asan'):
        r=validation[mode]
        lines.append(f"- {mode}: {r['passed']} passed, {r['skipped']} skipped, {r['failed']} failed, {r['error']} errors. Real M6 INT8 oracle and existing Metal parity passed.")
    lines += ["- Public C23/C++17 headers: "+validation['headers']['result']+"; requested INT8 with tensors disabled: "+validation['fallback']['result']+".", "- "+validation['format']+".", "- "+validation['gcc']+".", "",
              "[Validation metadata](raw/"+args.results.name+"/validation.json) includes commands and log hashes. "
              "Model logit/ID dump fingerprints are in `models/logit-manifest.json`. "
              "The isolated microbenchmark and model comparison revisions are recorded in their own metadata; "
              "later report/manifest generation does not change the measured kernels.", ""]
    args.out.write_text('\n'.join(lines))


if __name__ == '__main__':
    main()
