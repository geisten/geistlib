#!/usr/bin/env python3
"""Write src/engine/unicode_class.h from a llama.cpp checkout's
src/unicode-data.cpp (itself generated from the Unicode database).

The table classifies every codepoint >= 0x80 the way llama.cpp's regex
pretokenizers see it after collapsing (src/unicode.cpp, unicode_regex_split):
a letter (\\p{L}), a number (\\p{N}), punctuation (\\p{P}), a mark
(\\p{M}), a symbol (\\p{S}) or anything else. Whitespace is decided
by the caller from llama.cpp's short whitespace list. Same input, same output.

    tools/gen_unicode_classes.py ~/llama.cpp-cross-engine > src/engine/unicode_class.h
"""
import re
import subprocess
import sys
from pathlib import Path

root = Path(sys.argv[1]).expanduser()
src = (root / "src/unicode-data.cpp").read_text()
blk = src[src.index("unicode_ranges_flags"):src.index("unicode_set_whitespace")]
ranges = [(int(a, 16), int(b, 16)) for a, b in re.findall(r"\{0x([0-9A-F]+), 0x([0-9A-F]+)\}", blk)]
rev = subprocess.run(["git", "-C", str(root), "rev-parse", "--short=9", "HEAD"],
                     capture_output=True, text=True).stdout.strip()


def cls(flags: int) -> int:
    # llama.cpp's collapse keys on the whole category value (category_flag),
    # so a range with one of these single bits is that class, else other.
    return {0x0004: 1, 0x0002: 2, 0x0020: 3, 0x0010: 4, 0x0040: 5}.get(flags & 0x00FF, 0)


out, cur = [], 0
for start, flags in ranges:
    if start <= 0x80:
        cur = cls(flags)
        continue
    if not out:
        out.append((0x80, cur))
    c = cls(flags)
    if out[-1][1] != c:
        out.append((start, c))

vals = [(s << 3) | c for s, c in out]
print(f"""/*
 * src/engine/unicode_class.h - the class of every codepoint >= 0x80 as
 * llama.cpp's regex pretokenizers see it (#243, #242).
 *
 * Layer: ENGINE (internal). GENERATED by tools/gen_unicode_classes.py from
 * llama.cpp {rev} src/unicode-data.cpp (MIT; data from the Unicode
 * Character Database). Do not edit by hand.
 *
 * Each entry is (first codepoint << 3) | class, sorted; a range runs to the
 * next entry's start. Class 1 = \\p{{L}}, 2 = \\p{{N}}, 3 = \\p{{P}},
 * 4 = \\p{{M}}, 5 = \\p{{S}}, 0 = anything else (separators, controls,
 * unassigned). Whitespace is not in the table; the caller decides it first.
 */
#ifndef GEIST_INTERNAL_ENGINE_UNICODE_CLASS_H
#define GEIST_INTERNAL_ENGINE_UNICODE_CLASS_H

#include <stddef.h>
#include <stdint.h>

enum unicode_class : uint32_t {{
    UNICODE_CLASS_OTHER  = 0,
    UNICODE_CLASS_LETTER = 1,
    UNICODE_CLASS_NUMBER = 2,
    UNICODE_CLASS_PUNCT  = 3,
    UNICODE_CLASS_MARK   = 4,
    UNICODE_CLASS_SYMBOL = 5,
}};
static_assert(sizeof(enum unicode_class) == sizeof(uint32_t));

static const uint32_t UNICODE_CLASS_RANGES[] = {{""")
for i in range(0, len(vals), 7):
    print("        " + ", ".join(f"0x{v:07X}u" for v in vals[i:i + 7]) + ",")
print("""};

/* The class of cp >= 0x80 (binary search over the ranges). */
static inline enum unicode_class unicode_class_of(uint32_t cp) {
    size_t lo = 0, hi = sizeof UNICODE_CLASS_RANGES / sizeof UNICODE_CLASS_RANGES[0];
    while (hi - lo > 1) {
        const size_t mid = lo + (hi - lo) / 2;
        if ((UNICODE_CLASS_RANGES[mid] >> 3) <= cp)
            lo = mid;
        else
            hi = mid;
    }
    return (enum unicode_class)(UNICODE_CLASS_RANGES[lo] & 7u);
}

#endif /* GEIST_INTERNAL_ENGINE_UNICODE_CLASS_H */""")
